"""Regenerate the packaged offline demo fixture (synthetic data, deterministic).

The fixture mimics the *shape* of real Open-Meteo responses so that ``--demo``
exercises the same parser, service and renderer code as live mode. All weather
values are invented sample numbers; they are not observations or forecasts.
The location block reuses public GeoNames metadata for Yerevan as returned by
the Open-Meteo geocoding API.

Usage:  python scripts/generate_demo_fixture.py
"""

from __future__ import annotations

import json
import math
from datetime import datetime, timedelta
from pathlib import Path
from zoneinfo import ZoneInfo

OUT = Path(__file__).resolve().parents[1] / "src/weather_cli/demo/fixtures/yerevan_sample.json"
ZONE = ZoneInfo("Asia/Yerevan")
START = datetime(2026, 10, 1, tzinfo=ZONE)  # local midnight of the first sample day
SAMPLE_TIME = datetime(2026, 10, 1, 12, 0, tzinfo=ZONE)

DAY_MIN = [10.0, 11.0, 12.0, 13.0, 14.0, 15.0]
DAY_MAX = [19.0, 20.0, 21.0, 22.0, 23.0, 24.0]
DAY_CODE = [2, 1, 3, 61, 80, 0]
DAY_RAIN_CHANCE = [10, 5, 30, 70, 55, 0]
DAY_RAIN_SUM = [0.0, 0.0, 0.2, 6.5, 3.1, 0.0]
DAY_WIND_MAX = [14.0, 12.0, 18.0, 22.0, 26.0, 9.0]


def epoch(moment: datetime) -> int:
    return int(moment.timestamp())


def hourly_temperature(day: int, hour: int) -> float:
    """Smooth diurnal curve: minimum near 06:00, maximum near 15:00."""
    low, high = DAY_MIN[day], DAY_MAX[day]
    phase = math.cos((hour - 15) / 24 * 2 * math.pi)
    return round(low + (high - low) * (phase + 1) / 2, 1)


def build() -> dict[str, object]:
    hours = [START + timedelta(hours=i) for i in range(24 * len(DAY_MIN))]
    temps = [hourly_temperature(i // 24, i % 24) for i in range(len(hours))]
    is_day = [1 if 7 <= h.hour < 19 else 0 for h in hours]
    days = [START + timedelta(days=i) for i in range(len(DAY_MIN))]
    return {
        "_provenance": (
            "SYNTHETIC DEMONSTRATION DATA shaped like Open-Meteo API responses. "
            "Weather values are invented samples, not real observations or forecasts. "
            "Location metadata: GeoNames via Open-Meteo geocoding (CC BY 4.0). "
            "Generated by scripts/generate_demo_fixture.py."
        ),
        "geocoding": {
            "results": [
                {
                    "id": 616052,
                    "name": "Yerevan",
                    "latitude": 40.17765,
                    "longitude": 44.5126,
                    "elevation": 1002.0,
                    "feature_code": "PPLC",
                    "country_code": "AM",
                    "timezone": "Asia/Yerevan",
                    "population": 1144700,
                    "country": "Armenia",
                    "admin1": "Yerevan",
                }
            ]
        },
        "forecast": {
            "latitude": 40.17765,
            "longitude": 44.5126,
            "utc_offset_seconds": 14400,
            "timezone": "Asia/Yerevan",
            "timezone_abbreviation": "GMT+4",
            "elevation": 1002.0,
            "current_units": {
                "time": "unixtime",
                "temperature_2m": "°C",
                "relative_humidity_2m": "%",
                "apparent_temperature": "°C",
                "wind_speed_10m": "km/h",
                "wind_gusts_10m": "km/h",
                "pressure_msl": "hPa",
                "precipitation": "mm",
            },
            "current": {
                "time": epoch(SAMPLE_TIME),
                "interval": 900,
                "temperature_2m": 19.0,
                "relative_humidity_2m": 52,
                "apparent_temperature": 18.2,
                "weather_code": 2,
                "is_day": 1,
                "wind_speed_10m": 11.0,
                "wind_direction_10m": 315,
                "wind_gusts_10m": 24.5,
                "cloud_cover": 45,
                "pressure_msl": 1016.4,
                "precipitation": 0.0,
            },
            "hourly_units": {"time": "unixtime", "temperature_2m": "°C"},
            "hourly": {
                "time": [epoch(h) for h in hours],
                "temperature_2m": temps,
                "apparent_temperature": [round(t - 0.8, 1) for t in temps],
                "relative_humidity_2m": [round(80 - (t - 10) * 2.5) for t in temps],
                "precipitation_probability": [DAY_RAIN_CHANCE[i // 24] for i in range(len(hours))],
                "weather_code": [DAY_CODE[i // 24] for i in range(len(hours))],
                "wind_speed_10m": [
                    round(DAY_WIND_MAX[i // 24] * 0.6, 1) for i in range(len(hours))
                ],
                "is_day": is_day,
            },
            "daily_units": {"time": "unixtime", "temperature_2m_max": "°C"},
            "daily": {
                "time": [epoch(d) for d in days],
                "weather_code": DAY_CODE,
                "temperature_2m_max": DAY_MAX,
                "temperature_2m_min": DAY_MIN,
                "precipitation_probability_max": DAY_RAIN_CHANCE,
                "precipitation_sum": DAY_RAIN_SUM,
                "wind_speed_10m_max": DAY_WIND_MAX,
                "sunrise": [epoch(d.replace(hour=6, minute=56)) for d in days],
                "sunset": [epoch(d.replace(hour=18, minute=44)) for d in days],
            },
        },
    }


if __name__ == "__main__":
    OUT.write_text(json.dumps(build(), indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
